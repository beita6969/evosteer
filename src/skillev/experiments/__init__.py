def __getattr__(name: str) -> object:
    try:
        module_name, attribute = _LAZY_PUBLIC[name]
    except KeyError as error:
        raise AttributeError(name) from error
    value = getattr(import_module(module_name), attribute)
    globals()[name] = value
    return value
